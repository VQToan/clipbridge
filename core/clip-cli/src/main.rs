//! ClipBridge CLI (`clipbridge`)
//!
//! Command-line desktop client and diagnostic tool for ClipBridge:
//! an end-to-end encrypted (E2EE) cross-platform clipboard synchronization utility.

use std::path::PathBuf;

use anyhow::Result;
use clap::{Parser, Subcommand};
use clip_core::storage::History;
use tracing_subscriber::EnvFilter;

mod clipboard;
mod commands;
mod config;
mod sync;

use config::{AppConfig, AppPaths};

#[derive(Parser)]
#[command(
    name = "clipbridge",
    version,
    about = "ClipBridge: End-to-end encrypted cross-platform clipboard synchronization",
    long_about = "ClipBridge synchronizes your clipboard securely between devices using zero-knowledge \
                  WebSocket relays and end-to-end XChaCha20-Poly1305 encryption."
)]
struct Cli {
    /// Custom configuration and database directory (overrides default OS project directory)
    #[arg(long, env = "CLIPBRIDGE_HOME", global = true)]
    config_dir: Option<PathBuf>,

    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand)]
enum Commands {
    /// Initialize a new device group and generate pairing credentials
    Init {
        /// WebSocket relay URL (e.g. ws://127.0.0.1:18080 or wss://relay.example.com)
        #[arg(long)]
        relay: String,

        /// Human-readable device name (defaults to hostname/user)
        #[arg(long)]
        name: Option<String>,

        /// Overwrite existing configuration if already present
        #[arg(long)]
        force: bool,
    },

    /// Join an existing group using a pairing URI (clipbridge://pair?d=...)
    Join {
        /// The pairing URI generated by an existing group device
        uri: String,

        /// Human-readable device name (defaults to hostname/user)
        #[arg(long)]
        name: Option<String>,

        /// Overwrite existing configuration if already present
        #[arg(long)]
        force: bool,
    },

    /// Print the pairing URI for adding secondary devices to this group
    Pair,

    /// Publish a plain text clipboard payload to the group (one-shot)
    SendText {
        /// Plain text content to send
        text: String,
    },

    /// Publish an image file to the group (one-shot)
    SendImage {
        /// Path to the image file (PNG, JPEG, etc.)
        path: PathBuf,
    },

    /// Monitor and print received clipboard events without modifying the system clipboard
    Listen,

    /// Run the background clipboard synchronization daemon
    ///
    /// Note for Linux Wayland: Requires the wayland-data-control compositor protocol.
    /// The default GNOME Wayland compositor does not implement ext-data-control and
    /// is unsupported for background clipboard monitoring.
    Watch {
        /// Clipboard polling interval in milliseconds
        #[arg(long, default_value_t = 500)]
        poll_ms: u64,

        /// Disable image synchronization (text only)
        #[arg(long)]
        no_images: bool,
    },

    /// List recent clipboard history entries
    History {
        /// Maximum number of history entries to display
        #[arg(long, default_value_t = 20)]
        limit: usize,
    },

    /// Display current configuration and device status (without revealing secrets)
    Status,
}

#[tokio::main]
async fn main() -> Result<()> {
    tracing_subscriber::fmt()
        .with_env_filter(
            EnvFilter::try_from_default_env().unwrap_or_else(|_| EnvFilter::new("info")),
        )
        .with_writer(std::io::stderr)
        .init();

    let cli = Cli::parse();
    let paths = AppPaths::resolve(cli.config_dir.as_deref())?;

    match cli.command {
        Commands::Init { relay, name, force } => {
            commands::cmd_init(&paths, relay, name, force)?;
        }
        Commands::Join { uri, name, force } => {
            commands::cmd_join(&paths, &uri, name, force)?;
        }
        Commands::Pair => {
            commands::cmd_pair(&paths)?;
        }
        Commands::SendText { text } => {
            commands::cmd_send_text(&paths, &text).await?;
        }
        Commands::SendImage { path } => {
            commands::cmd_send_image(&paths, &path).await?;
        }
        Commands::Listen => {
            commands::cmd_listen(&paths).await?;
        }
        Commands::Watch { poll_ms, no_images } => {
            let cfg = AppConfig::load(&paths.config_file)?;
            paths.ensure_dirs()?;
            let history = History::open(&paths.history_db)?;
            sync::run_watch(cfg, history, poll_ms, no_images).await?;
        }
        Commands::History { limit } => {
            commands::cmd_history(&paths, limit)?;
        }
        Commands::Status => {
            commands::cmd_status(&paths)?;
        }
    }

    Ok(())
}
